-- ==============================================================================
-- RESTA : CONFIGURATION DE LA MESSAGERIE EN DIRECT AVEC RÉPONSE, MODIFICATION & SUPPRESSION
-- ==============================================================================
-- Exécutez ce script dans l'Éditeur SQL de votre tableau de bord Supabase :
-- (Dashboard Supabase > SQL Editor > New query > Run)

-- 1. Création de la table des messages si elle n'existe pas
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL DEFAULT 1,
    client_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    client_nom TEXT DEFAULT 'Client',
    expediteur_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    expediteur_role TEXT NOT NULL CHECK (expediteur_role IN ('client', 'admin')),
    texte TEXT NOT NULL,
    lu BOOLEAN DEFAULT FALSE,
    modifie BOOLEAN DEFAULT FALSE,
    supprime_pour_tous BOOLEAN DEFAULT FALSE,
    supprime_par TEXT[] DEFAULT '{}',
    reponse_a_id BIGINT,
    reponse_a_nom TEXT,
    reponse_a_texte TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Ajout des nouvelles colonnes si la table existait déjà
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS modifie BOOLEAN DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS supprime_pour_tous BOOLEAN DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS supprime_par TEXT[] DEFAULT '{}';
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS reponse_a_id BIGINT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS reponse_a_nom TEXT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS reponse_a_texte TEXT;

-- 3. Index de performance
CREATE INDEX IF NOT EXISTS idx_messages_restaurant_client ON public.messages(restaurant_id, client_id);
CREATE INDEX IF NOT EXISTS idx_messages_client_id ON public.messages(client_id);
CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at);

-- 4. Activation du REPLICA IDENTITY FULL (requis pour Supabase Realtime UPDATE/DELETE)
ALTER TABLE public.messages REPLICA IDENTITY FULL;

-- 5. Publication Realtime pour la table messages
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'messages'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
    END IF;
END $$;

-- 6. Sécurisation de la table admins
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins peuvent lire leur statut" ON public.admins;
CREATE POLICY "Admins peuvent lire leur statut" ON public.admins
    FOR SELECT
    TO authenticated
    USING (auth.uid() = user_id);

-- 7. Activation de la sécurité RLS sur 'messages'
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lecture des messages autorisée pour participants" ON public.messages;
DROP POLICY IF EXISTS "Insertion des messages pour participants" ON public.messages;
DROP POLICY IF EXISTS "Mise a jour du statut lu" ON public.messages;
DROP POLICY IF EXISTS "Modification et statut des messages" ON public.messages;
DROP POLICY IF EXISTS "Suppression des messages" ON public.messages;

-- A) LECTURE :
CREATE POLICY "Lecture des messages autorisée pour participants" ON public.messages
    FOR SELECT
    TO authenticated
    USING (
        auth.uid() = client_id OR
        EXISTS (
            SELECT 1 FROM public.admins
            WHERE admins.user_id = auth.uid()
            AND (admins.restaurant_id IS NULL OR admins.restaurant_id::text = messages.restaurant_id::text)
        )
    );

-- B) INSERTION :
CREATE POLICY "Insertion des messages pour participants" ON public.messages
    FOR INSERT
    TO authenticated
    WITH CHECK (auth.uid() = expediteur_id);

-- C) MODIFICATION (Texte, statut lu, suppression pour tous) :
CREATE POLICY "Modification et statut des messages" ON public.messages
    FOR UPDATE
    TO authenticated
    USING (
        auth.uid() = expediteur_id OR
        auth.uid() = client_id OR
        EXISTS (
            SELECT 1 FROM public.admins
            WHERE admins.user_id = auth.uid()
            AND (admins.restaurant_id IS NULL OR admins.restaurant_id::text = messages.restaurant_id::text)
        )
    )
    WITH CHECK (
        auth.uid() = expediteur_id OR
        auth.uid() = client_id OR
        EXISTS (
            SELECT 1 FROM public.admins
            WHERE admins.user_id = auth.uid()
            AND (admins.restaurant_id IS NULL OR admins.restaurant_id::text = messages.restaurant_id::text)
        )
    );

-- D) SUPPRESSION DÉFINITIVE :
CREATE POLICY "Suppression des messages" ON public.messages
    FOR DELETE
    TO authenticated
    USING (
        auth.uid() = expediteur_id OR
        EXISTS (SELECT 1 FROM public.admins WHERE admins.user_id = auth.uid())
    );
